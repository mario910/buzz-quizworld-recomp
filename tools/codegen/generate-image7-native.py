"""Image 7 (Sofdec YUV->RGB consumer, spu_0006_at_007E7500): native float for
its hot conversion loop 0x8638 only.

In the menu's video scene this one function keeps an SPU thread ~75% busy.
Image 7 as a whole uses double precision elsewhere, so it cannot run under the
RZ/FTZ/DAZ environment the native single-precision helpers need. 0x8638 itself
is single precision only (cuflt, fs, fma, cfltu, shufb), has no channel, stop
or halt, and leaves only through a tail jump to 0x8F70 -- so the environment
can be scoped to that function.

Output (analysis/native-image7/):
  spu_recomp.c   the pinned lift; 0x8638 renamed ..._reference, a wrapper under
                 the original name hands calls to buzz_image7_run (port code)
  kernel_8638.c  the same body as buzz_image7_8638_native, compiled with
                 SPU_NATIVE_RTZ (+ result guard): hardware ops under RZ, exact
                 lane repair as everywhere else in the lift
Reproducible derived output: never edit port/spu.
"""

from pathlib import Path as _Path
import sys as _sys
_sys.path.insert(0, str(_Path(__file__).resolve().parents[2]))
from pathlib import Path
import hashlib
import re
import shutil

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "analysis/native-image7"
PROFILES = (
    ("spu_0006_at_007E7500", "8638", "8F70", "614c795eb0004d69f5df66ff6962a379d506df5549f15e778a765be2f89c233a"),
    ("spu_0006_at_007FF780", "86B8", "8FF0", "91aa78e6de6c31734d0c639e5b9ff14790a7bad50990f804d5d7f8af40733f0c"),
)
found = [p for p in PROFILES if (ROOT / "port/spu" / p[0] / "spu_recomp.c").exists()]
if len(found) != 1:
    raise SystemExit("Expected one reviewed video image profile; clean stale generated images")
image, pc, exit_pc, PIN = found[0]
SOURCE = ROOT / "port/spu" / image
NAME = image + "_spu_func_0000" + pc

raw = (SOURCE / "spu_recomp.c").read_bytes()
if hashlib.sha256(raw).hexdigest() != PIN:
    raise SystemExit("Image 7 reference changed: re-audit before generating")
source = raw.decode("utf-8")
match = re.search(rf"(?m)^void {NAME}\(spu_context\* ctx\) \{{", source)
if not match:
    raise SystemExit(f"missing {NAME}")
body_end = source.index("\n}", match.end())
body = source[match.end():body_end]
if re.search(r"spu_(?:df\w*|fesd|frds|fscr\w*)\(", body):
    raise SystemExit("0x8638 uses double precision: RTZ unsafe")
if re.search(r"spu_(?:rdch|wrch|rchcnt|stop|halt)|spu_drain_call|SPU_RET", body):
    raise SystemExit("0x8638 has channel/stop/call exits: MXCSR scope unsafe")
exits = set(re.findall(r"g_spu_trampoline_fn = (\w+);", body))
if exits != {image + "_spu_func_0000" + exit_pc}:
    raise SystemExit(f"unexpected exits {exits}")

wrapper = f"""
extern void buzz_image7_8638_native(spu_context* ctx);
extern void buzz_image7_run(spu_context* ctx, void (*reference)(spu_context*),
                            void (*native)(spu_context*));
extern int buzz_image7_mode;
void {NAME}(spu_context* ctx) {{
    if (!buzz_image7_mode) {{ {NAME}_reference(ctx); return; }}
    buzz_image7_run(ctx, {NAME}_reference, buzz_image7_8638_native);
}}
"""
lift = (source[:match.start()] + f"void {NAME}_reference(spu_context* ctx) {{" + body + "\n}\n"
        + wrapper + source[body_end + 2:])
includes = "".join(line + "\n" for line in source.splitlines() if line.startswith("#include"))
kernel = (f"/* Generated by generate-image7-native.py: body of {NAME}, native RTZ. */\n"
          + includes + f"\nvoid buzz_image7_8638_native(spu_context* ctx) {{" + body + "\n}\n")
OUT.mkdir(parents=True, exist_ok=True)
(OUT / "spu_recomp.c").write_text(lift, encoding="utf-8", newline="\n")
(OUT / "kernel_8638.c").write_text(kernel, encoding="utf-8", newline="\n")
shutil.copyfile(SOURCE / "spu_recomp.h", OUT / "spu_recomp.h")
print(f"Image 7: pinned lift + native 0x8638 kernel -> {OUT}")
