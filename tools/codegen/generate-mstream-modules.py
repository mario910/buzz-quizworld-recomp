"""Lift the code MultiStream (the game's SPU audio mixer) loads at runtime.

MultiStream copies position-independent modules into its own local store and
calls them: the firmware ATRAC decoder (/dev_flash/sys/external/flashATRAC.pic)
and the game's DSP plugins (embedded in the EBOOT; extracted to
analysis/spu-images). No SPU image contains them, so before this they could
only run through the SDK interpreter (SPU_INTERP_UNLIFTED, ~1.1 CPU core).

Each module is lifted at the LS address MultiStream loads it to (observed with
SPU_UNLIFTED_LSDUMP; the modules have no relocations) and registered with
spu_runtime_code_register(): the runtime hashes the span on first entry and
uses the lift only if the bytes match, otherwise it keeps interpreting.

Inputs are pinned by SHA-256 of the module .text; output goes to the ignored
analysis/mstream-modules (firmware and game code never enter the repository).
Usage: tools/codegen/generate-mstream-modules.py --dev-flash <PS3 dev_flash directory>
"""

from pathlib import Path as _Path
import sys as _sys
_sys.path.insert(0, str(_Path(__file__).resolve().parents[2]))
from pathlib import Path
import argparse
import hashlib
import struct
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
TOOLS = ROOT / "ps3recomp/tools"
sys.path.insert(0, str(TOOLS))
from wrap_spu_elf import wrap  # noqa: E402

OUT = ROOT / "analysis/mstream-modules"
FIRST_IMAGE_ID = 50

# name, source, LS base, entries seen called, mutable window
# (offsets into .text the program overwrites after first use; init code).
MODULES = (
    ("atrac", "dev_flash:sys/external/flashATRAC.pic",
     0x32B10, (0x32B10, 0x36DD8), (0x53C0, 0x53D0)),
    ("compressor", "analysis/spu-images/spu_0003_at_0071F480.elf",
     0x2FE10, (0x2FE10, 0x304F0), (0, 0)),
    ("vumeter", "analysis/spu-images/spu_0005_at_00722680.elf",
     0x2FA10, (0x2FA10, 0x2FA70), (0, 0)),   # 0x2FA70: multi-player games
)
PINNED = {
    "atrac": "c543ecc87e82beec3159d88fbb73dc4229424d357c0a48be3c4cb55d3fdefadc",
    "compressor": "7afc1a08a0536176a9a6a7f2ff0749c5581dec1f18caf2aaae7640d5a382c0d7",
    "vumeter": "e6cd56546fe5ff596e009077fd028f9b5e71ce1d1046832f9f578dbeef205d1a",
}


def text_section(path):
    data = path.read_bytes()
    shoff = struct.unpack_from(">I", data, 0x20)[0]
    entsize, count, strndx = struct.unpack_from(">HHH", data, 0x2E)
    headers = [struct.unpack_from(">10I", data, shoff + i * entsize) for i in range(count)]
    strtab = headers[strndx][4]
    for header in headers:
        name = data[strtab + header[0]:data.index(b"\0", strtab + header[0])]
        if name == b".text":
            return data[header[4]:header[4] + header[5]]
    raise SystemExit(f"{path}: no .text")


def fnv64(chunks):
    h = 0xCBF29CE484222325
    for chunk in chunks:
        for byte in chunk:
            h = ((h ^ byte) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--dev-flash", required=True)
    parser.add_argument("--print-hashes", action="store_true")
    args = parser.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    register = ["/* GENERATED by generate-mstream-modules.py: runtime-loaded MultiStream code. */",
                "#include <stdint.h>",
                "extern void spu_begin_image(int image_id);",
                "extern void spu_runtime_code_register(uint32_t lsa, uint32_t size, uint32_t skip_lo,",
                "                                      uint32_t skip_hi, uint64_t fnv, int image_id);"]
    from launcher import paths as buzz_paths
    digest = hashlib.sha256(buzz_paths.eboot_elf().read_bytes()).hexdigest()
    modules, pins = MODULES, PINNED
    if digest in ("6b07344c81a669174586ea637634f3b522eb91a7824e9e88623581b88d0405a8",
                  "fb78b9e6d30ba5eaa76b7e31bc3afa838736dcb5cde40fc602a628f2305ebb5d"):
        # Actual 1.00 runtime entries, not a PPU address relocation. Dispatch
        # still verifies the complete immutable LS bytes before using a lift.
        # US extraction uses hash-checked canonical names for identical EU roles.
        modules = (
            ("atrac", "dev_flash:sys/external/flashATRAC.pic", 0x32890, (0x32890, 0x36B58), (0x53C0, 0x53D0)),
            ("compressor", "analysis/spu-images/spu_0003_at_00737100.elf", 0x2FB90, (0x2FB90, 0x30278), (0, 0)),
            ("vumeter", "analysis/spu-images/spu_0005_at_0073A180.elf", 0x2F7F0, (0x2F7F0,), (0, 0)),
        )
        pins = dict(PINNED, compressor="64fa006a8073a801d87fd816926189a15cbac8ffb8d67cf5fe78adce1e711f05",
                    vumeter="c3a67640bca66ef439648e609637d52b3bfe830f6c0182207cc97440c89b89c0")
    elif digest != buzz_paths.EXPECTED_ELF_SHA256:
        raise SystemExit("Unreviewed executable family for MultiStream modules")
    body = []
    for index, (name, source, base, entries, (skip_lo, skip_hi)) in enumerate(modules):
        path = (Path(args.dev_flash) / source[len("dev_flash:"):] if source.startswith("dev_flash:")
                else ROOT / source)
        if not path.exists():
            raise SystemExit(f"missing {path}")
        text = text_section(path)
        digest = hashlib.sha256(text).hexdigest()
        if args.print_hashes:
            print(name, digest)
            continue
        if digest != pins[name]:
            raise SystemExit(f"{name}: .text sha256 {digest} is not the audited module")
        image = FIRST_IMAGE_ID + index
        prefix = f"buzz_mstream_{name}_"
        elf = OUT / f"{name}.elf"
        elf.write_bytes(wrap(text, base=base, entry=entries[0]))
        command = [sys.executable, str(TOOLS / "spu_lifter.py"), "--auto-functions", str(elf),
                   "--base", hex(base), "--symbol-prefix", prefix, "-o", str(OUT / name),
                   "--source-name", "spu_recomp.c", "--header-name", "spu_recomp.h",
                   "--extra-funcs", ",".join(hex(e) for e in entries)]
        result = subprocess.run(command, capture_output=True, text=True)
        if result.returncode:
            raise SystemExit(f"{name}: lifter failed\n{result.stderr}")
        source_c = (OUT / name / "spu_recomp.c").read_text(encoding="utf-8")
        if "unsupported" in source_c.lower() and "spu_unsupported" in source_c:
            raise SystemExit(f"{name}: lift contains unsupported instructions")
        size = len(text)
        h = fnv64((text[:skip_lo], text[skip_hi:])) if skip_hi else fnv64((text,))
        register.append(f"extern void {prefix}spu_recomp_register(void);")
        body.append(f"    spu_begin_image({image}); {prefix}spu_recomp_register();")
        body.append(f"    spu_runtime_code_register(0x{base:05X}u, 0x{size:X}u, 0x{skip_lo:X}u, "
                    f"0x{skip_hi:X}u, 0x{h:016X}ull, {image});")
        print(f"{name}: LS 0x{base:05X}+0x{size:X} -> image {image}, {result.stdout.strip().splitlines()[-1]}")
    if args.print_hashes:
        return
    register += ["", "static void buzz_mstream_register(void)", "{"] + body + [
        "    spu_begin_image(0);", "}",
        "/* Before the game starts MultiStream (as spu_workloads.c registers images). */",
        "__attribute__((constructor)) static void buzz_mstream_init(void) { buzz_mstream_register(); }", ""]
    (OUT / "mstream_register.c").write_text("\n".join(register), encoding="utf-8", newline="\n")
    print(f"-> {OUT}")


if __name__ == "__main__":
    main()
