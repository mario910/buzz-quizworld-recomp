"""Extract and lift verified raw SPURS jobs from the Quiz World 1.02 ELF.

Raw job images start with a 16-byte GUID, not an ELF header. Their normal
entry is +0x10. Keep the registration separate from the embedded ELF registry.
"""

from pathlib import Path as _Path
import sys as _sys
_sys.path.insert(0, str(_Path(__file__).resolve().parents[2]))
from pathlib import Path
import json
import hashlib
import struct
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
TOOLS = ROOT / "ps3recomp/tools"
sys.path.insert(0, str(TOOLS))
from spu_disasm import disassemble_spu
from build_spu_workloads import debase_includes, fnv1a64
from find_spu_functions import (collect_branch_targets,
    collect_link_register_targets, collect_computed_branch_targets,
    collect_jump_table_targets)

sys.path.insert(0, str(ROOT))
from launcher import paths as buzz_paths
ELF = buzz_paths.eboot_elf()
blob = ELF.read_bytes()
if hashlib.sha256(blob).hexdigest() != buzz_paths.EXPECTED_ELF_SHA256:
    raise ValueError("Expected the verified BCES00647 update 1.02 ELF")
phoff = struct.unpack_from(">Q", blob, 32)[0]
phsize, phcount = struct.unpack_from(">HH", blob, 54)


def read_va(va, size):
    for i in range(phcount):
        typ, flags, off, addr, _, filesz, memsz, align = struct.unpack_from(
            ">IIQQQQQQ", blob, phoff + i * phsize)
        if typ == 1 and addr <= va and va + size <= addr + filesz:
            return blob[off + va - addr:off + va - addr + size]
    raise ValueError(f"Unmapped ELF address {va:#x}+{size:#x}")


# eaBinary and size verified in the live job descriptor; executable end from
# disassembly (last return at 0x898, followed by alignment and shuffle constants).
jobs = [("buzz_signal", 0x7E9F80, 2224, 0x10, 0x8A0)]
# First seen in live SPURS descriptors (SPU_DUMP_MISS); every one is stored
# whole in the ELF at the file offset below, so the user's own ELF is the only
# input. They include large constant tables; only the verified instruction
# prefix is lifted as code.
ELF_OFFSET = {
    "2B4BFE75F8010C62": 0x72D800, "68748F08DB209F16": 0x753980,
    "D2C1D22722462449": 0x7AB100, "14B49831F6E7B504": 0x77D100,
    "40B5435765A8CA07": 0x7DC980, "39D91C54E170307C": 0x7AA680,
    "C0BCF712A5047048": 0x74C280, "ABE18CA0D02ED5B4": 0x722D00,
    "6EBA872A91705ED9": 0x76EC00, "B3AE64B096A3A10F": 0x737280,
    "19D0E2A7CC1A0B3B": 0x741680, "D6902C586B38C6E9": 0x7C2200,
}
captured = [
    ("buzz_job_2b4b", "2B4BFE75F8010C62", 39552, 0x9D0),
    ("buzz_job_6874", "68748F08DB209F16", 111232, 0x20B0),
    ("buzz_job_d2c1", "D2C1D22722462449", 55776, 0xD80),
    ("buzz_job_14b4", "14B49831F6E7B504", 185728, 0x1D70),
    ("buzz_job_40b5", "40B5435765A8CA07", 43824, 0xA540),
    # Reached after supplying R1.word1 (SPU ABI available stack size).
    ("buzz_job_39d9", "39D91C54E170307C", 2576, 0x920),
    ("buzz_job_c0bc", "C0BCF712A5047048", 30416, 0x5B50),
    # Edge animation variant reached when loading the next scene.
    ("buzz_job_abe1", "ABE18CA0D02ED5B4", 43696, 0xA410),
    ("buzz_job_6eba", "6EBA872A91705ED9", 58624, 0xCB80),
    # First 3D frontend scene after the logo/intro movies. Last returns at
    # 0x9210/0xA650, followed by alignment and strings/shuffle constants.
    ("buzz_job_b3ae", "B3AE64B096A3A10F", 41984, 0x9220),
    ("buzz_job_19d0", "19D0E2A7CC1A0B3B", 43968, 0xA660),
    # Reached on entry to game/players, not the menu-only smoke path.
    # Last code block branches back at 0x5190, lnop 0x5194; data starts 0x51A0.
    ("buzz_job_d690", "D6902C586B38C6E9", 38112, 0x5198),
]
# Code addresses the heuristics cannot see: loaded as constants and reached
# through a register later. Without an entry the runtime interprets them on
# every visit (found in a menu profile: spu_interp_run_until).
EXTRA_STARTS = {
    # ila $r22, 0xB90 at 0xB18 and ila $r75, 0x4E0 at 0x328: continuations after bi/br
    "buzz_job_d2c1": [0x4E0, 0xB90],
    # Indirect-call targets reached through function pointers, observed with
    # SPU_INTERP_ENTRIES=1 in the menu (6.6-9 M interpreted instructions/s,
    # mostly images 40/41). Images 37/40/43 share one library routine set at
    # shifted offsets (identical first words).
    "buzz_job_6eba": [0x2978, 0x2E60, 0x3550, 0x35F8, 0x3608, 0x38F8],
    "buzz_job_abe1": [0x1394, 0x14A8, 0x1EF4, 0x2140, 0x232C, 0x25E8, 0x2764],
    "buzz_job_40b5": [0x140C, 0x1520, 0x1F6C, 0x21B8, 0x23A4, 0x2660, 0x27DC],
    "buzz_job_19d0": [0x1524, 0x1638, 0x2084, 0x22D0, 0x24BC, 0x2778, 0x28F4],
}
out = ROOT / "analysis/raw-jobs"
out.mkdir(exist_ok=True)
registrations = ['/* Generated by generate-raw-jobs.py. */',
                 '#include "spu_workload.h"',
                 'extern void spu_begin_image(int);']
calls = []
inputs = [(name, read_va(va, size), entry, end) for name, va, size, entry, end in jobs]
for name, fingerprint, size, end in captured:
    offset = ELF_OFFSET[fingerprint]
    data = blob[offset:offset + size]
    if len(data) != size or fnv1a64(data) != int(fingerprint, 16):
        raise ValueError(f"Unexpected raw job contents at ELF offset {offset:#x}: {name}")
    inputs.append((name, data, 0x10, end))
for index, (name, data, entry, end) in enumerate(inputs, 32):
    raw = out / (name + ".bin")
    raw.write_bytes(data)
    starts = {entry}
    instructions = list(disassemble_spu(data[:end], 0))
    # Non-call branches also introduce entries: the CRT jumps to main past
    # helper routines, whose earlier returns otherwise truncate the raw bound.
    starts.update(a for a in (collect_branch_targets(instructions)
        | collect_link_register_targets(instructions)
        | collect_computed_branch_targets(instructions)
        | collect_jump_table_targets(instructions, data, 0, end)) if entry <= a < end)
    starts.update(EXTRA_STARTS.get(name, []))
    for insn in instructions:
        if insn.mnemonic in ("brsl", "brasl"):
            target = int(insn.operands.split(",")[-1].strip(), 0)
            if entry <= target < end and target != insn.addr + 4:
                starts.add(target)
    starts = sorted(starts)
    bounds = out / (name + ".functions.json")
    bounds.write_text(json.dumps([dict(start=hex(a), end=hex(b))
        for a, b in zip(starts, starts[1:] + [end])], indent=2))
    # Generate beside references first; copy only changed outputs so adding a
    # captured job does not rebuild every unrelated large lifted source.
    dest = ROOT / "port/spu" / name
    generated = out / "generated" / name
    subprocess.run([sys.executable, str(TOOLS / "spu_lifter.py"), str(raw),
        "--functions", str(bounds), "--output", str(generated),
        "--symbol-prefix", name + "_", "--code-end", hex(end)], check=True)
    dest.mkdir(parents=True, exist_ok=True)
    for filename in ("spu_recomp.h", "spu_recomp.c"):
        source = generated / filename
        debase_includes(source)
        target = dest / filename
        contents = source.read_bytes()
        if not target.exists() or target.read_bytes() != contents:
            target.write_bytes(contents)
    symbol = f"{name}_spu_func_{entry:08X}"
    registrations += [f"extern void {symbol}(spu_context*);",
                      f"extern void {name}_spu_recomp_register(void);"]
    calls += [f"    spu_begin_image({index}); {name}_spu_recomp_register();",
              f'    spu_workload_register_img(0x{fnv1a64(data):016X}ULL, '
              f'{symbol}, {index}, "{name}");']
    print(f"{name}: size={len(data)} entry={entry:04X} "
          f"fingerprint={fnv1a64(data):016X}")
registrations += ['__attribute__((constructor)) static void buzz_raw_jobs_register(void)',
                  '{'] + calls + ['    spu_begin_image(0);', '}', '']
(ROOT / "port/spu/jobmods_register.c").write_text("\n".join(registrations))
