"""Differential real-runtime checks for the CMake-generated job-return adapter."""
import argparse
import os
from pathlib import Path
import subprocess
import tempfile

p=argparse.ArgumentParser(description=__doc__)
p.add_argument('--channels-source',required=True,type=Path)
p.add_argument('--arm64',action='store_true')
args=p.parse_args()
root=Path(__file__).resolve().parents[2];sdk=root/'ps3recomp';spu=sdk/'runtime/spu'
source=args.channels_source.resolve()
if not source.is_file() or 'buzz_spu_complete_job_return' not in source.read_text():
    p.error('--channels-source must be generated by CMake with BUZZ_SPU_JOB_RETURN=ON')
if os.name=='nt' and args.arm64:p.error('ARM64 correctness uses the Linux/QEMU toolchain')
compiler='aarch64-linux-gnu-gcc' if args.arm64 else os.environ.get('CC','clang-cl' if os.name=='nt' else 'cc')
runner=['qemu-aarch64','-L','/usr/aarch64-linux-gnu'] if args.arm64 else []
sources=['spu_drain.c','spu_lockstep.c','spu_coherency.c','spu_workload.c','spurs_policy.c',
         'spurs_job.c','spurs_job_ls.c','spu_tsp_weak.c','spu_vm_pagemap.c','spurs_policy_blob_weak.c','spu_interp.c']
modes=['simple','direct','queued-direct','lifted-direct','nested-depth','inner','queued-inner','irq-frame','irq-enabled','wrong-link',
       'host-return','foreign-ls','observer','registered','policy','irq-restore','overlay','resident-code',
       'fp-state','fp-x87','inner-fp']
modes+=['sdk-'+x for x in ['top','top-zero','nested-return','nested-return-unlifted','nested-calls',
       'stop-zero','nested-stop','stop-code','halt','smc','pure-interpreter','stepcap','negative-stepcap']]
with tempfile.TemporaryDirectory(prefix='buzz-job-return-') as temp:
    binary=Path(temp)/('test.exe' if os.name=='nt' else 'test')
    includes=[sdk/'include',spu,sdk/'runtime/platform',root/'port']
    inputs=[root/'tests/spu-job-return-test.c',source,*[spu/name for name in sources],
            sdk/'runtime/platform/win32_compat.c',sdk/'libs/system/host_controls.c']
    if os.name=='nt':
        command=[compiler,'/nologo','/std:c17','/MD','/O2','/UNDEBUG','/W0',
            *['/I'+str(x) for x in includes],*[str(x) for x in inputs],'/Fo'+str(Path(temp))+os.sep,
            '/Fe'+str(binary),'/link','user32.lib','advapi32.lib','ole32.lib','winmm.lib','synchronization.lib']
    else:
        command=[compiler,'-std=gnu17','-O2','-UNDEBUG',*['-I'+str(x) for x in includes],
                 *[str(x) for x in inputs],'-pthread','-lm','-o',str(binary)]
    subprocess.run(command,check=True)
    for mode in modes:
        outputs=[]
        for enabled in ('0','1'):
            env={k:v for k,v in os.environ.items() if not k.startswith(('SPU_','SPURS_','YDKJ_','LBP_','GH3_','BUZZ_'))}
            env['BUZZ_SPU_JOB_RETURN']=enabled
            if mode in ('sdk-stepcap','sdk-negative-stepcap'):env.update(YDKJ_SPU_TRACE='1',SPU_STEPCAP='2')
            result=subprocess.run([*runner,str(binary),mode],cwd=temp,env=env,capture_output=True,text=True,timeout=15)
            if result.returncode:
                raise RuntimeError(f'{mode}/{enabled} failed: {result.stdout}\n{result.stderr[-4000:]}')
            outputs.append(result.stdout)
        if outputs[0]!=outputs[1]:raise RuntimeError(f'Job return mismatch {mode}: {outputs}')
        print(outputs[0].strip())
    print(f'PASS {len(modes)} real-runtime modes OFF/ON: nesting, IRQ, policy, raw LS, registered targets, interpreter and stop/halt; QEMU is correctness only')
