#include "hle_nids.h"
#include <QDir>
#include <QFileInfo>
#include <QMap>
#include <QRegularExpression>
#include <QSet>

namespace prepare {
namespace {
quint32 functionNid(const QString &name) {
    static const auto suffix = QByteArray::fromHex("6759659904250490566427499489741a");
    const auto digest = QCryptographicHash::hash(name.toUtf8() + suffix, QCryptographicHash::Sha1);
    return qFromLittleEndian<quint32>(digest.constData());
}
} // namespace

int writeHleNids(const QString &sdk, const QString &output, const Cancel &cancel) {
    const QDir libs(QDir(sdk).filePath("libs"));
    static const QStringList directories{"system", "filesystem", "input", "audio", "video", "network",
                                         "spurs",  "sync",       "codec", "font",  "misc",  "hardware"};
    QMap<QString, QString> modules;
    for (const auto &directory : directories) {
        const QDir dir(libs.filePath(directory));
        for (const auto &file :
             dir.entryList({"cell*.c", "sce*.c", "sys*.c"}, QDir::Files | QDir::CaseSensitive)) {
            require(!modules.contains(file), "Ambiguous HLE module: " + file);
            modules.insert(file, dir.filePath(file));
        }
    }
    require(!modules.isEmpty(), "No SDK HLE modules found in " + libs.path());

    static const QRegularExpression definition(
        R"rx(^(?!static)[A-Za-z_][\w \t\*]*?\b(_?(?:cell|sys|sce|_sys)\w+)\s*\([^;]*?\)\s*\{)rx",
        QRegularExpression::MultilineOption | QRegularExpression::UseUnicodePropertiesOption);
    QSet<quint32> seen;
    QStringList declarations, registrations;
    bool saveData = false;
    for (const auto &path : std::as_const(modules)) {
        cancelled(cancel);
        const auto source = QString::fromLatin1(readFile(path));
        auto matches = definition.globalMatch(source);
        while (matches.hasNext()) {
            const auto name = matches.next().captured(1);
            const auto nid = functionNid(name);
            if (seen.contains(nid))
                continue;
            seen.insert(nid);
            saveData |= name == "cellSaveDataListAutoLoad";
            declarations.append("    void " + name + "(void);");
            registrations.append("    ps3_hle_register(0x" +
                                 QString::number(nid, 16).toUpper().rightJustified(8, '0') + "u, \"" + name +
                                 "\", (void*)" + name + ");");
        }
    }
    require(!seen.isEmpty(), "No HLE handlers found.");
    QStringList lines{
        "/* Auto-generated by BuzzPrepare -- do not edit. */",
        "extern \"C\" void ps3_hle_register(unsigned int nid, const char* name, void* handler);",
        "extern \"C\" {"};
    lines.append(declarations);
    lines.append("}");
    if (saveData)
        lines.append(
            {"struct ppu_context;", "extern \"C\" void ps3_savedata_list_auto_load(ppu_context*);",
             "extern \"C\" void ps3_hle_register_ctx(unsigned, const char*, void (*)(ppu_context*));"});
    lines.append("extern \"C\" void ppu_hle_register_all(void) {");
    lines.append(registrations);
    if (saveData)
        lines.append("    ps3_hle_register_ctx(0x21425307u, \"cellSaveDataListAutoLoad\", "
                     "ps3_savedata_list_auto_load);");
    lines.append({"}", ""});
    atomicWrite(QFileInfo(output).absolutePath(), output, lines.join('\n').toUtf8(), cancel);
    return seen.size();
}
} // namespace prepare
