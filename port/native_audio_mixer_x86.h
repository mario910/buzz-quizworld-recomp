#pragma once
#include "native_stagef_avx2.h"

/* Called under the mixer's scoped RTZ/FTZ/DAZ environment. Two independent
 * groups of four samples share a checked operation and exceptional-lane repair. */
static inline void audio_split_pair(v8 result, u128* low, u128* high)
{
    *low = rtz_store(_mm256_castsi256_si128(result));
    *high = rtz_store(_mm256_extracti128_si256(result, 1));
}

static inline u128 audio_signed_bytes(u128 words)
{
    return rtz_store(_mm_srai_epi32(_mm_slli_epi32(rtz_load(words), 24), 24));
}

/* CWD selects one destination word for the preferred (first) SPU word. */
static inline __m128i audio_sample_mask(unsigned address)
{
    return _mm_cmpeq_epi32(_mm_setr_epi32(0, 1, 2, 3), _mm_set1_epi32((address >> 2) & 3));
}

static inline u128 audio_insert_sample(u128 sample, u128 original, __m128i mask)
{
    const __m128i broadcast = _mm_shuffle_epi32(rtz_load(sample), 0);
    return rtz_store(_mm_blendv_epi8(rtz_load(original), broadcast, mask));
}

/* PSHUFB zeros a lane whose high control bit is set. Build both input
 * selectors and the generated bytes once for all iterations of the loop. */
typedef struct { __m128i a, b, generated; } audio_shuffle_mask;

static inline audio_shuffle_mask audio_prepare_shuffle(u128 selector)
{
    const __m128i c = rtz_load(selector);
    const __m128i index = _mm_xor_si128(_mm_and_si128(c, _mm_set1_epi8(15)), _mm_set1_epi8(3));
    const __m128i from_b = _mm_slli_epi16(_mm_and_si128(c, _mm_set1_epi8(16)), 3);
    const __m128i high = _mm_set1_epi8((char)0x80);
    const __m128i special = _mm_and_si128(c, high);
    const __m128i ones = _mm_cmpeq_epi8(_mm_and_si128(c, _mm_set1_epi8((char)0xe0)),
                                        _mm_set1_epi8((char)0xc0));
    const __m128i e0 = _mm_cmpeq_epi8(_mm_or_si128(c, _mm_set1_epi8(31)), _mm_set1_epi8(-1));
    const audio_shuffle_mask mask = {
        _mm_or_si128(index, _mm_or_si128(special, from_b)),
        _mm_or_si128(index, _mm_or_si128(special, _mm_andnot_si128(from_b, high))),
        _mm_or_si128(ones, _mm_and_si128(e0, high))
    };
    return mask;
}

static inline u128 audio_shuffle_samples(u128 a, u128 b, audio_shuffle_mask mask)
{
    return rtz_store(_mm_or_si128(mask.generated, _mm_or_si128(
        _mm_shuffle_epi8(rtz_load(a), mask.a), _mm_shuffle_epi8(rtz_load(b), mask.b))));
}

/* CFLTS at scale 16. Positive values >= 32768 saturate, including SPU
 * extended numbers. Negative overflow returns INT_MIN with CVTTPS2DQ. */
static inline u128 audio_pcm_fixed16(u128 value)
{
    const __m128i bits = rtz_load(value);
    const __m128 scaled = _mm_mul_ps(_mm_castsi128_ps(bits), _mm_set1_ps(65536.0f));
    return rtz_store(_mm_blendv_epi8(_mm_cvttps_epi32(scaled), _mm_set1_epi32(INT32_MAX),
                                     _mm_cmpgt_epi32(bits, _mm_set1_epi32(0x46ffffff))));
}

static inline int audio_copy_quads(spu_context* ctx, u128* count, u128* source,
                                   u128* dest, u128* last, u128* condition)
{
    const uint32_t bytes = count->_u32[0] & ~15u;
    const uint32_t src = source->_u32[0] & (SPU_LS_MASK & ~15u);
    const uint32_t dst = dest->_u32[0] & (SPU_LS_MASK & ~15u);
    if (!bytes || bytes > SPU_LS_SIZE - src || bytes > SPU_LS_SIZE - dst ||
        (dst > src && dst - src < bytes))
        return 0;
    *last = spu_ls_read128(ctx, src + bytes - 16);
    memmove(ctx->ls + dst, ctx->ls + src, bytes);
    const __m128i increment = _mm_set1_epi32((int)bytes);
    *count = rtz_store(_mm_sub_epi32(rtz_load(*count), increment));
    *source = rtz_store(_mm_add_epi32(rtz_load(*source), increment));
    *dest = rtz_store(_mm_add_epi32(rtz_load(*dest), increment));
    *condition = spu_clgti(*count, 15);
    return 1;
}

static inline void audio_product8(u128 a, u128 b, u128 c, u128 d, u128* low, u128* high)
{
    audio_split_pair(v8_fm(v8_pair(a, c), v8_pair(b, d)), low, high);
}

static inline v8 audio_pair_sum(v8 left, v8 right)
{
    const __m256 sum = _mm256_add_ps(_mm256_castsi256_ps(left), _mm256_castsi256_ps(right));
    return v8_finish(sum, left, right, left, 0);
}

static inline void audio_sum8(u128 a, u128 b, u128 c, u128 d, u128* low, u128* high)
{
    audio_split_pair(audio_pair_sum(v8_pair(a, c), v8_pair(b, d)), low, high);
}

static inline void audio_difference8(u128 a, u128 b, u128 c, u128 d, u128* low, u128* high)
{
    audio_split_pair(v8_fs(v8_pair(a, c), v8_pair(b, d)), low, high);
}

static inline void audio_fma8(u128 a, u128 b, u128 c, u128 d, u128 e, u128 f, u128* low, u128* high)
{
    audio_split_pair(v8_fma(v8_pair(a, d), v8_pair(b, e), v8_pair(c, f)), low, high);
}

static inline void audio_mix8(u128 gain, u128 a, u128 b, u128 c, u128 d, u128* low, u128* high)
{
    audio_split_pair(v8_fma(v8_bcast(gain), v8_pair(a, c), v8_pair(b, d)), low, high);
}

/* The two levels of the mixer's 4x4 word transpose use four masks.
 * Byte selectors below are in guest word order. An alternate selector
 * must execute the original shuffle, including generated-byte controls. */
static inline int audio_fft_transpose_masks(const spu_context* ctx)
{
    const __m128i low_words = _mm_setr_epi32(0x00010203, 0x10111213, 0x04050607, 0x14151617);
    const __m128i low_pairs = _mm_setr_epi32(0x00010203, 0x04050607, 0x10111213, 0x14151617);
    const __m128i eight = _mm_set1_epi8(8);
    const __m128i words = _mm_or_si128(_mm_xor_si128(rtz_load(ctx->gpr[33]), low_words),
        _mm_xor_si128(rtz_load(ctx->gpr[31]), _mm_add_epi8(low_words, eight)));
    const __m128i pairs = _mm_or_si128(_mm_xor_si128(rtz_load(ctx->gpr[29]), low_pairs),
        _mm_xor_si128(rtz_load(ctx->gpr[28]), _mm_add_epi8(low_pairs, eight)));
    const __m128i mismatch = _mm_or_si128(words, pairs);
    return _mm_testz_si128(mismatch, mismatch);
}

/* Signed PCM scaled by 2^-31. Signed conversion in RTZ is exact to the
 * guest's precision, and the power-of-two scale cannot underflow. */
static inline void audio_pcm8(u128 a, u128 b, u128* low, u128* high)
{
    const __m256 samples = _mm256_cvtepi32_ps(v8_pair(a, b));
    audio_split_pair(_mm256_castps_si256(_mm256_mul_ps(samples, _mm256_set1_ps(0x1p-31f))), low, high);
}

static inline v8 audio_swap_halves(v8 pair)
{
    return _mm256_permute2x128_si256(pair, pair, 0x01);
}

static inline v8 audio_opposite_twiddle(v8 pair)
{
    const v8 sign = _mm256_set_m128i(_mm_setzero_si128(), _mm_set1_epi32(INT32_MIN));
    return _mm256_xor_si256(pair, sign);
}

/* The final iteration in the retained guest loop produces the outgoing scratch GPRs. */
static inline void audio_fft_butterfly_prefix(spu_context* ctx, unsigned rounds)
{
    const v8 twiddle25 = v8_bcast(ctx->gpr[25]);
    const v8 twiddle26 = v8_bcast(ctx->gpr[26]);
    const v8 twiddle23 = v8_bcast(ctx->gpr[23]);
    const v8 twiddle24 = v8_bcast(ctx->gpr[24]);
    const v8 twiddle28_27 = v8_pair(ctx->gpr[28], ctx->gpr[27]);
    const v8 twiddle27_28 = audio_swap_halves(twiddle28_27);
    unsigned a = ctx->gpr[16]._u32[0], b = ctx->gpr[17]._u32[0];
    unsigned y = ctx->gpr[18]._u32[0], x = ctx->gpr[19]._u32[0];

    for (unsigned i = 0; i < rounds; ++i, a += 64, b += 64, y += 64, x += 64) {
        // The four streams may overlap. Read the whole iteration before its first store.
        const v8 left = v8_pair(spu_ls_read128(ctx, x), spu_ls_read128(ctx, y));
        const v8 right = v8_pair(spu_ls_read128(ctx, b + 16), spu_ls_read128(ctx, a + 16));
        const v8 low = v8_pair(spu_ls_read128(ctx, a), spu_ls_read128(ctx, b));
        const v8 high = v8_pair(spu_ls_read128(ctx, a + 32), spu_ls_read128(ctx, b + 32));

        const v8 even = audio_pair_sum(left, right);
        const v8 odd = v8_fs(left, right);
        const v8 even_pair = audio_swap_halves(audio_pair_sum(low, high));
        const v8 odd_pair = v8_fs(low, high);
        const v8 sums = audio_pair_sum(even, even_pair);
        const v8 difference = v8_fs(even, even_pair);
        const v8 plus = audio_pair_sum(odd, odd_pair);
        const v8 minus = v8_fs(odd, odd_pair);

        const v8 rotated0 = v8_fma(audio_swap_halves(difference), twiddle26,
                                   audio_opposite_twiddle(v8_fm(difference, twiddle25)));
        const v8 minus_low = _mm256_permute2x128_si256(minus, minus, 0x00);
        const v8 plus_high = _mm256_permute2x128_si256(plus, plus, 0x11);
        const v8 rotated1 = v8_fma(plus_high, twiddle28_27,
                                   audio_opposite_twiddle(v8_fm(minus_low, twiddle27_28)));
        const v8 plus_minus = _mm256_permute2x128_si256(plus, minus, 0x30);
        const v8 rotated2 = v8_fma(audio_swap_halves(plus_minus), twiddle24,
                                   audio_opposite_twiddle(v8_fm(plus_minus, twiddle23)));

        spu_ls_write128(ctx, y, rtz_store(_mm256_extracti128_si256(sums, 1)));
        spu_ls_write128(ctx, a + 16, rtz_store(_mm256_castsi256_si128(rotated1)));
        spu_ls_write128(ctx, a, rtz_store(_mm256_castsi256_si128(rotated0)));
        spu_ls_write128(ctx, a + 32, rtz_store(_mm256_castsi256_si128(rotated2)));
        spu_ls_write128(ctx, x, rtz_store(_mm256_castsi256_si128(sums)));
        spu_ls_write128(ctx, b, rtz_store(_mm256_extracti128_si256(rotated0, 1)));
        spu_ls_write128(ctx, b + 16, rtz_store(_mm256_extracti128_si256(rotated1, 1)));
        spu_ls_write128(ctx, b + 32, rtz_store(_mm256_extracti128_si256(rotated2, 1)));
    }
    for (unsigned reg = 16; reg <= 19; ++reg)
        ctx->gpr[reg] = spu_ai(ctx->gpr[reg], 64 * rounds);
    ctx->gpr[22] = spu_ai(ctx->gpr[22], -(int)rounds);
}
